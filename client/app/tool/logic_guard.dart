/// Enforces PLAN L15 ("Dart holds no logic") in the Flutter workspace:
///
/// 1. **Dependency allow-list.** Every workspace package may depend only on
///    the Flutter stack of PLAN §11.1 (plus a few packages allowed in one
///    specific package, e.g. `intl` for gen-l10n in `strata_l10n`). Anything
///    else fails, with a reason for well-known offenders (HTTP clients,
///    databases, key-value stores, file-system access).
/// 2. **Dart file locations.** Dart files may only live in `lib/`, `test/`
///    or `tool/` of a package (or be generated code).
///
/// Run with `dart run tool/logic_guard.dart [workspace-root]` (melos:
/// `melos run logic-guard`). Exits with 1 when a violation is found.
library;

